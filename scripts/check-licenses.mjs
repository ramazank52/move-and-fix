import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { evaluateSpdxExpression, normalizeDeclaredLicense } from "./license-policy.mjs";

const root = join(process.cwd(), "node_modules");

async function licenseFromFile(packageDirectory) {
  const entries = await readdir(packageDirectory, { withFileTypes: true });
  const licenseFile = entries.find((entry) => entry.isFile() && /^(license|copying)(\.|$)/i.test(entry.name));
  if (!licenseFile) return "UNKNOWN";
  const text = (await readFile(join(packageDirectory, licenseFile.name), "utf8")).slice(0, 1500).toLowerCase();
  if (text.includes("apache license") && text.includes("version 2.0")) return "Apache-2.0";
  if (text.includes("permission is hereby granted, free of charge")) return "MIT";
  if (text.includes("mozilla public license") && text.includes("2.0")) return "MPL-2.0";
  if (text.includes("redistribution and use in source and binary forms")) return "BSD-3-Clause";
  return "UNKNOWN";
}

async function listPackageDirectories() {
  const entries = await readdir(root, { withFileTypes: true });
  const packageDirectories = [];
  for (const entry of entries.filter((candidate) => candidate.isDirectory() && !candidate.name.startsWith("."))) {
    if (entry.name.startsWith("@")) {
      const scoped = await readdir(join(root, entry.name), { withFileTypes: true });
      packageDirectories.push(...scoped.filter((candidate) => candidate.isDirectory()).map((candidate) => join(root, entry.name, candidate.name)));
    } else {
      packageDirectories.push(join(root, entry.name));
    }
  }
  return packageDirectories;
}

const packageDirectories = await listPackageDirectories();
const findings = [];
const evaluatedPackages = [];

for (const packageDirectory of packageDirectories) {
  try {
    const manifest = JSON.parse(await readFile(join(packageDirectory, "package.json"), "utf8"));
    const declared = normalizeDeclaredLicense(manifest.license);
    const license = declared === "UNKNOWN" ? await licenseFromFile(packageDirectory) : declared;
    const evaluation = evaluateSpdxExpression(license);
    const component = { name: manifest.name, version: manifest.version, license, ...evaluation };
    evaluatedPackages.push(component);
    if (!evaluation.allowed) findings.push(`${manifest.name}@${manifest.version}: ${license} (${evaluation.reason})`);
  } catch {
    // Broken or absent manifests are owned by package-manager integrity validation.
  }
}

const sortedPackages = evaluatedPackages.sort((left, right) => `${left.name}@${left.version}`.localeCompare(`${right.name}@${right.version}`));
const apacheComponents = sortedPackages.filter((component) => component.selected.some((selection) => selection.license === "Apache-2.0"));
const notices = [
  "# Third-Party Notices",
  "",
  "This inventory is generated by `pnpm supply:licenses`. Apache-2.0 components may require preservation of upstream NOTICE material and attribution in downstream distributions.",
  "",
  "## Apache-2.0 components detected",
  "",
  ...(apacheComponents.length > 0 ? apacheComponents.map((component) => `- ${component.name}@${component.version} — declared SPDX: ${component.license}`) : ["- None detected."]),
  "",
  "For each listed component, release packaging must preserve the component's upstream license and NOTICE files when supplied. This inventory does not replace upstream license text.",
  "",
].join("\n");

await mkdir(join(process.cwd(), "artifacts"), { recursive: true });
await writeFile(join(process.cwd(), "artifacts", "THIRD_PARTY_NOTICES.md"), notices, "utf8");
await writeFile(
  join(process.cwd(), "artifacts", "license-policy-report.json"),
  `${JSON.stringify({ generatedAt: new Date().toISOString(), packageCount: sortedPackages.length, findings: findings.sort(), packages: sortedPackages }, null, 2)}\n`,
  "utf8",
);

if (findings.length > 0) {
  console.error("Disallowed or unclassified dependency licenses:\n" + findings.sort().join("\n"));
  process.exit(1);
}

console.log(`SPDX license policy passed for ${packageDirectories.length} installed packages. Attribution inventory: artifacts/THIRD_PARTY_NOTICES.md`);
